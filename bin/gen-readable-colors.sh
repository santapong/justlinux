#!/usr/bin/env python3
"""Derive READABLE module tints from the wallpaper's own palette.

The problem this solves: wallust's ansi slots carry the wallpaper's hues,
which is exactly what makes the desktop feel matched — but their lightness
is whatever the photo happened to contain. On the current wallpaper @red
lands at 1.00:1 against the background and @magenta at 1.80:1, so a module
tinted with them is invisible.

Pinning fixed colours would fix legibility and lose the wallpaper link.
Instead this keeps each slot's HUE and SATURATION and moves only its
LIGHTNESS until it clears the contrast target. The bar still changes colour
with the wallpaper; it just stops going invisible.

Writes ~/.config/<app>/tokens.css with an `ok-` prefixed twin of every slot:

    @define-color ok-red  #E0808A;   /* @red, lifted to 4.5:1 */

Run after `wallust run` (wallpaper.sh does). Idempotent.
"""
import colorsys
import re
import sys
from pathlib import Path

HOME = Path.home()
TARGETS = [HOME / ".config/waybar", HOME / ".config/swaync"]
SLOTS = ("red", "green", "yellow", "magenta", "cyan", "accent", "surface")
TARGET_RATIO = 4.5
MAX_STEPS = 60


def _lin(c):
    return c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4


def lum(rgb):
    r, g, b = rgb
    return 0.2126 * _lin(r) + 0.7152 * _lin(g) + 0.0722 * _lin(b)


def ratio(a, b):
    la, lb = lum(a), lum(b)
    hi, lo = max(la, lb), min(la, lb)
    return (hi + 0.05) / (lo + 0.05)


def to_rgb(h):
    h = h.lstrip("#")
    return tuple(int(h[i:i + 2], 16) / 255 for i in (0, 2, 4))


def to_hex(rgb):
    return "#" + "".join(f"{max(0, min(255, round(c * 255))):02X}" for c in rgb)


def make_readable(hexcol, bg_hex, target=TARGET_RATIO):
    """Same hue, same saturation, lightness walked until it clears `target`.

    Direction is chosen by the ground: on a dark background we lighten, on a
    light one we darken. If a hue simply cannot reach the target before it
    hits white/black, the closest attempt is returned — better a colour that
    is nearly readable than a silent failure.
    """
    rgb, bg = to_rgb(hexcol), to_rgb(bg_hex)
    if ratio(rgb, bg) >= target:
        return hexcol, False
    h, l, s = colorsys.rgb_to_hls(*rgb)
    up = lum(bg) < 0.5
    best, best_r = rgb, ratio(rgb, bg)
    for i in range(1, MAX_STEPS + 1):
        step = i / MAX_STEPS
        nl = l + (1.0 - l) * step if up else l * (1.0 - step)
        cand = colorsys.hls_to_rgb(h, nl, s)
        r = ratio(cand, bg)
        if r > best_r:
            best, best_r = cand, r
        if r >= target:
            return to_hex(cand), True
    return to_hex(best), True


def defined(text):
    return dict(re.findall(r"@define-color\s+([\w-]+)\s+(#[0-9a-fA-F]{6})",
                           text))


def main():
    quiet = "--quiet" in sys.argv
    for app in TARGETS:
        src = app / "colors.css"
        if not src.exists():
            continue
        C = defined(src.read_text())
        bg = C.get("base") or C.get("background")
        if not bg:
            continue
        out = ["/* GENERATED by gen-readable-colors.sh — do not edit.",
               " * The wallpaper's own hues with their lightness corrected to",
               f" * at least {TARGET_RATIO}:1 against the background, so a module",
               " * tint follows the wallpaper without ever going invisible.",
               " */"]
        fixed = []
        for slot in SLOTS:
            if slot not in C:
                continue
            new, changed = make_readable(C[slot], bg)
            note = f"  /* @{slot} {C[slot]} lifted */" if changed else ""
            out.append(f"@define-color ok-{slot} {new};{note}")
            if changed:
                fixed.append(f"{slot} {C[slot]}→{new}")
        (app / "tokens.css").write_text("\n".join(out) + "\n")
        if not quiet:
            print(f"{app.name}/tokens.css: {len(SLOTS)} tints"
                  + (f" — corrected {', '.join(fixed)}" if fixed
                     else " — none needed correcting"))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
