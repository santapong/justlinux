SIZES = {24: ICONS_24, 16: ICONS_16}


def draw(cr, name, x, y, size=16, scale=1):
    """Blit an icon at (x, y). The caller sets the colour first —
    cr.set_source_rgb(*rgb(PAL['accent2'])) then draw(...) — which
    is what keeps these wallust-driven. An unknown size falls back
    to the smallest generated one rather than raising."""
    art = (SIZES.get(size) or SIZES[min(SIZES)]).get(name)
    if not art:
        return 0
    for ry, row in enumerate(art):
        run = 0
        for rx, ch in enumerate(row):
            if ch == 'X':
                run += 1
                continue
            if run:            # one rect per run, not per pixel
                cr.rectangle(x + (rx - run) * scale,
                             y + ry * scale, run * scale, scale)
                run = 0
        if run:
            cr.rectangle(x + (len(row) - run) * scale,
                         y + ry * scale, run * scale, scale)
    cr.fill()
    return size * scale
